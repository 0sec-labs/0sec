import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";

const [sourceDir = "packages/dashboard/dist", outputFile = "packages/cli/src/dashboard-assets.generated.ts"] = process.argv.slice(2);
const sourceRoot = sourceDir.replace(/[\\/]$/, "");

if (!existsSync(join(sourceRoot, "index.html"))) {
  throw new Error(`Dashboard assets not found at ${sourceRoot}; build @0sec/dashboard first.`);
}

function listFiles(dir) {
  const entries = readdirSync(dir, { withFileTypes: true })
    .sort((left, right) => left.name.localeCompare(right.name));
  const files = [];
  for (const entry of entries) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...listFiles(path));
    else if (entry.isFile()) files.push(path);
  }
  return files;
}

const assets = listFiles(sourceRoot).map((path) => {
  const relativePath = relative(sourceRoot, path).split(sep).join("/");
  return [`/${relativePath}`, readFileSync(path).toString("base64")];
});

const source = [
  "export type EmbeddedDashboardAsset = readonly [relativePath: string, contentBase64: string];",
  "",
  "/** Generated by packages/cli/scripts/generate-dashboard-assets.mjs. */",
  "export const DASHBOARD_ASSETS: readonly EmbeddedDashboardAsset[] = [",
  ...assets.map(([path, content]) => `  [${JSON.stringify(path)}, ${JSON.stringify(content)}],`),
  "] as const;",
  "",
].join("\n");

mkdirSync(dirname(outputFile), { recursive: true });
writeFileSync(outputFile, source, "utf8");
console.log(`Embedded ${assets.length} dashboard assets from ${sourceRoot}.`);
