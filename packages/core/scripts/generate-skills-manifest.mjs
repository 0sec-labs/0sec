#!/usr/bin/env node
/**
 * generate-skills-manifest.mjs — inline every JIT skill YAML into a bundled TS
 * module so skills survive `bun --compile`.
 *
 * The skill loader (src/agent/skills/index.ts) discovers skills by walking its
 * own directory for *.yaml at runtime. That works from a source checkout or the
 * on-disk esbuild bundle, but NOT in the single-file binary: `bun --compile`
 * bakes imported modules, never files read via readdirSync, so the packaged
 * binary's walk hits an empty virtual FS and loads ZERO skills.
 *
 * This script reads the YAML tree and emits `src/agent/skills/skills.generated.ts`
 * exporting the raw YAML text keyed by repo-relative path. Because that's a real
 * import, it is bundled/baked into the binary; the loader falls back to it when
 * no YAML is found on disk. Checked in (like pricing.oss.generated.ts) and
 * regenerated on build; a drift test keeps it in sync.
 *
 * Run:  node packages/core/scripts/generate-skills-manifest.mjs
 * Or:   pnpm --filter @0sec/core generate-skills
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SKILLS_DIR = join(__dirname, "..", "src", "agent", "skills");
const OUT = join(SKILLS_DIR, "skills.generated.ts");

function walkYaml(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walkYaml(p));
    else if (entry.name.endsWith(".yaml") || entry.name.endsWith(".yml")) out.push(p);
  }
  return out;
}

// Deterministic order so regeneration is diff-stable.
const files = walkYaml(SKILLS_DIR).sort();

const entries = files.map((abs) => {
  const rel = relative(SKILLS_DIR, abs).split("\\").join("/");
  const raw = readFileSync(abs, "utf8");
  // JSON.stringify yields a safe, fully-escaped TS string literal.
  return `  ${JSON.stringify(rel)}: ${JSON.stringify(raw)},`;
});

const body = `// AUTO-GENERATED by scripts/generate-skills-manifest.mjs. DO NOT EDIT BY HAND.
// Refresh: pnpm --filter @0sec/core generate-skills
//
// Inlines every JIT skill YAML so the loader can register skills inside a
// \`bun --compile\` binary, where readdirSync of the skills dir returns nothing.
// The on-disk loader path (source checkout / node dist bundle) is still primary;
// this manifest is the fallback used when no YAML is found on disk.

export const EMBEDDED_SKILL_YAML: Record<string, string> = {
${entries.join("\n")}
};
`;

writeFileSync(OUT, body);
console.log(`Wrote ${files.length} embedded skills → ${relative(join(__dirname, ".."), OUT)}`);
